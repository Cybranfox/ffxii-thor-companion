local load_, xpcall_, pcall_, tostring_, type_ = load, xpcall, pcall, tostring, type
local s_format, s_match, s_sub, s_byte, s_char, s_rep, s_gsub, s_find = string.format, string.match, string.sub,
  string.byte, string.char, string.rep, string.gsub, string.find
local t_concat = table.concat
local G = _G
local lfs_ = rawget(G, "lfs")

