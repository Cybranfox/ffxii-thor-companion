--ThorCompanion.lua: the loader for the FFXII Thor Companion (https://github.com/Cybranfox/ffxii-thor-companion).
--Installed once into the game's x64/scripts folder by install.cmd. At every game start it reads the companion's game
--script (the "core") from Download/FFXII_companion/install, checks its Ed25519 signature against the keys pinned
--below, refuses anything older than what it has already accepted, and only then runs it. Unsigned, altered, older or
--unknown-key files are never run; the game then simply starts without the companion. Every decision is reported in
--Download/FFXII_companion/live/loader_status.json.
--Design: docs/SECURITY.md and Secure_Loader_Design (project notes). The signature check (verify) is pure Lua, MIT,
--not independently audited. This file is generated by scripts/build_stub.py from game-script/loader/stub.lua.

local STUB_VERSION = 1
