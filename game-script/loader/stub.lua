local BASE_DIR = "D:/FFXII_companion/"
local CORE_FILE = BASE_DIR .. "install/ThorCompanion-core.lua"
local SIG_FILE = BASE_DIR .. "install/ThorCompanion-core.sig"
local POLICY_FILE = BASE_DIR .. "install/ThorCompanion-policy.txt"
local STATUS_FILE = BASE_DIR .. "live/loader_status.json"
--Private to the game install (GameNative keeps the game folder in its own app storage): the rollback journal and any
--accepted key-rotation policy. Relative to the game's x64 folder, like every other script path.
local STATE_DIR = "scripts/ThorCompanion-state/"
local SLOTS = { STATE_DIR .. "journal_a.txt", STATE_DIR .. "journal_b.txt" }
local PRIVATE_POLICY = STATE_DIR .. "policy.txt"
local MAX_CORE, MAX_SIG, MAX_POLICY, MAX_JOURNAL = 524288, 512, 512, 2048
local INT_MAX = 2147483647

local function hexbytes(h) return (s_gsub(h, "..", function(v) return s_char(tonumber(v, 16)) end)) end
local function tohex(s) return (s_gsub(s, ".", function(c) return s_format("%02x", s_byte(c)) end)) end
local function sha512hex(s) return tohex(verify.sha512(s)) end
--A key ID is the first 16 hex characters (8 bytes) of the raw public key; the full pinned key is what is checked.

--Bounded single read: at most cap + 1 bytes, so an oversized file is detected without reading it all.
local function readOnce(path, cap)
  local f = io_open(path, "rb")
  if not f then return nil, "missing" end
  local data = f:read(cap + 1)
  f:close()
  if data == nil then data = "" end
  if #data > cap then return nil, "oversize" end
  return data
end

local function decimal(s)
  if not s or #s > 10 or not s_match(s, "^[1-9][0-9]*$") then return nil end
  local n = tonumber(s)
  if not n or n > INT_MAX then return nil end
  return n
end

local function validDate(date)
  local y, m, d = s_match(date or "", "^(%d%d%d%d)%-(%d%d)%-(%d%d)$")
  y, m, d = tonumber(y), tonumber(m), tonumber(d)
  if not y or y < 1 or not m or m < 1 or m > 12 or not d then return false end
  local days = { 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31 }
  if y % 4 == 0 and (y % 100 ~= 0 or y % 400 == 0) then days[2] = 29 end
  return d >= 1 and d <= days[m]
end

--Status receipt for the companion app (advisory: it lives in shared storage).
local function jsonString(s) return '"' .. s_gsub(tostring_(s), '[%c"\\]', function(c) return s_format("\\u%04x", s_byte(c)) end) .. '"' end
local function writeStatus(t)
  local parts = {}
  for _, k in ipairs({ "contract", "stub", "result", "version", "sequence", "keyId", "epoch", "verifyMs", "detail", "wallTime" }) do
    local v = t[k]
    if v ~= nil then parts[#parts + 1] = jsonString(k) .. ":" .. (type_(v) == "number" and s_format("%d", v) or jsonString(v)) end
  end
  local text = "{" .. t_concat(parts, ",") .. "}"
  if #text > 4096 then return end
  if lfs_ and lfs_.mkdir then pcall_(lfs_.mkdir, BASE_DIR .. "live") end
  local f = io_open(STATUS_FILE, "w")
  if f then f:write(text); f:close() end
end

local function status(result, extra)
  local t = { contract = "ffxii.loader.v1", stub = STUB_VERSION, result = result, wallTime = os_time() }
  for k, v in pairs(extra or {}) do t[k] = v end
  pcall_(writeStatus, t)
end

-------------------------------------------------------------------------------------------------- policy (key rotation)
--FFXII-ROOT-POLICY-V1 / epoch / release-key / min-sequence / build-date, signed by the RECOVERY key (never by a release
--key). It names the one release key accepted from that epoch on and the lowest core sequence it accepts.
local function parsePolicy(text)
  if type_(text) ~= "string" or #text > MAX_POLICY then return nil, "policy_format" end
  local epoch, key, minSeq, date, sig = s_match(text,
    "^FFXII%-ROOT%-POLICY%-V1\nepoch=([1-9][0-9]*)\nrelease%-key=([0-9a-f]+)\nmin%-sequence=([1-9][0-9]*)\nbuild%-date=([0-9%-]+)\n([0-9a-f]+)\n$")
  if not epoch or #key ~= 64 or #sig ~= 128 or not validDate(date) then return nil, "policy_format" end
  epoch, minSeq = decimal(epoch), decimal(minSeq)
  if not epoch or not minSeq then return nil, "policy_format" end
  local signed = s_sub(text, 1, #text - 129)
  if not verify.verify(hexbytes(PINS.recovery_key), signed, hexbytes(sig)) then return nil, "policy_signature" end
  return { epoch = epoch, release_key = key, min_sequence = minSeq, digest = sha512hex(text), text = text }
end

local FACTORY = { epoch = 1, release_key = PINS.release_key, min_sequence = PINS.min_sequence, digest = s_rep("0", 128) }

------------------------------------------------------------------------------------------------------- rollback journal
local JOURNAL_FIELDS = { "generation", "policy-epoch", "policy-sha512", "key-id", "sequence", "message-sha512" }

local function parseJournal(text)
  if type_(text) ~= "string" or #text > MAX_JOURNAL then return nil end
  local lines = {}
  for line in text:gmatch("([^\n]*)\n") do lines[#lines + 1] = line end
  if #lines ~= 8 or lines[1] ~= "FFXII-STATE-V1" then return nil end
  local j, body = {}, "FFXII-STATE-V1\n"
  for i, name in ipairs(JOURNAL_FIELDS) do
    local k, v = s_match(lines[i + 1], "^([%w%-]+)=([%w]+)$")
    if k ~= name then return nil end
    j[name] = v
    body = body .. lines[i + 1] .. "\n"
  end
  local ck = s_match(lines[8], "^checksum=([0-9a-f]+)$")
  if not ck or ck ~= sha512hex(body) or text ~= body .. lines[8] .. "\n" then return nil end
  j.generation, j.epoch, j.sequence = decimal(j.generation), decimal(j["policy-epoch"]), tonumber(j.sequence)
  if not j.generation or not j.epoch or not j.sequence or j.sequence < 0 then return nil end
  return j
end

local function journalText(j)
  local body = "FFXII-STATE-V1\n" .. s_format("generation=%d\npolicy-epoch=%d\npolicy-sha512=%s\nkey-id=%s\nsequence=%d\nmessage-sha512=%s\n",
    j.generation, j.epoch, j["policy-sha512"], j["key-id"], j.sequence, j["message-sha512"])
  return body .. "checksum=" .. sha512hex(body) .. "\n"
end

--The newest valid slot; "absent" when neither slot file exists (fresh install), "corrupt" when files exist but none is valid.
local function loadJournal()
  local best, seen = nil, false
  for _, path in ipairs(SLOTS) do
    local text = readOnce(path, MAX_JOURNAL)
    if text then
      seen = true
      local j = parseJournal(text)
      if j and (not best or j.generation > best.generation) then best = j; best.slot = path end
    end
  end
  if best then return best end
  return nil, seen and "corrupt" or "absent"
end

--Write the next generation to the slot NOT holding the current one, then read it back.
local function saveJournal(cur, j)
  j.generation = (cur and cur.generation or 0) + 1
  local path = (cur and cur.slot == SLOTS[1]) and SLOTS[2] or SLOTS[1]
  local text = journalText(j)
  if lfs_ and lfs_.mkdir then pcall_(lfs_.mkdir, s_sub(STATE_DIR, 1, -2)) end
  local f = io_open(path, "wb")
  if not f then return false end
  local ok = f:write(text)
  f:close()
  if not ok then return false end
  local back = readOnce(path, MAX_JOURNAL)
  if back ~= text then return false end
  j.slot = path
  return true
end

local function saveFile(path, text)
  local f = io_open(path, "wb")
  if not f then return false end
  local ok = f:write(text)
  f:close()
  return ok and readOnce(path, MAX_POLICY) == text
end

----------------------------------------------------------------------------------------------------------------- start
local function run()
  if _VERSION ~= "Lua 5.4" or math.maxinteger ~= 0x7fffffffffffffff then return status("unsupported_lua") end
  if rawget(G, "__ffxii_companion_loader") then return status("already_loaded") end
  G.__ffxii_companion_loader = true

  --1. Private state: the accepted policy and the rollback journal.
  local policy = FACTORY
  local privText = readOnce(PRIVATE_POLICY, MAX_POLICY)
  if privText then
    local p, why = parsePolicy(privText)
    if not p then return status("state_corrupt", { detail = why }) end
    policy = p
  end
  local journal, jwhy = loadJournal()
  if not journal and jwhy == "corrupt" then return status("state_corrupt", { detail = "journal" }) end
  if journal and (journal.epoch ~= policy.epoch or journal["policy-sha512"] ~= policy.digest) then
    return status("state_corrupt", { detail = "journal_policy" })
  end

  --2. A newer key-rotation policy staged by the app (signed by the recovery key) is adopted before the core is checked.
  local staged = readOnce(POLICY_FILE, MAX_POLICY)
  if staged then
    local p = parsePolicy(staged)
    if p and p.epoch > policy.epoch then
      if not saveFile(PRIVATE_POLICY, staged) then return status("state_unwritable", { detail = "policy" }) end
      local j = { epoch = p.epoch, ["policy-sha512"] = p.digest, ["key-id"] = s_sub(p.release_key, 1, 16),
                  sequence = p.min_sequence - 1, ["message-sha512"] = s_rep("0", 128) }
      if not saveJournal(journal, j) then return status("state_unwritable", { detail = "journal" }) end
      policy, journal = p, j
    end
  end

  local floor = journal and journal.sequence or (policy.min_sequence - 1)
  local floorDigest = journal and journal["message-sha512"] or s_rep("0", 128)

  --3. Read the signature envelope and the core exactly once each.
  local packet, pwhy = readOnce(SIG_FILE, MAX_SIG)
  local core, cwhy = readOnce(CORE_FILE, MAX_CORE)
  if not packet or not core then
    local why = not packet and ("sig_" .. pwhy) or ("core_" .. cwhy)
    return status((pwhy == "oversize" or cwhy == "oversize") and "bad_format" or "missing", { detail = why })
  end

  --4. Strict format, then the signature over the exact header lines + the exact core bytes.
  if #core == 0 or s_sub(core, 1, 3) == "\239\187\191" or s_find(core, "\r", 1, true) or s_find(core, "\0", 1, true)
     or s_sub(core, -1) ~= "\n" or s_byte(core, 1) == 27 then return status("bad_format", { detail = "core_text" }) end
  local seq, version, minStub, date, kid, length, sig = s_match(packet,
    "^FFXII%-CORE%-SIG%-V1\nsequence=([1-9][0-9]*)\nversion=([0-9a-z.%-]+)\nmin%-stub=([1-9][0-9]*)\nbuild%-date=([0-9%-]+)\nkey%-id=([0-9a-f]+)\nlength=([1-9][0-9]*)\n([0-9a-f]+)\n$")
  if not seq or #kid ~= 16 or #sig ~= 128 or #version > 64
     or not (s_match(version, "^%d+%.%d+%.%d+$") or s_match(version, "^%d+%.%d+%.%d+%-[a-z0-9.]+$"))
     or not validDate(date) then return status("bad_format", { detail = "envelope" }) end
  seq, minStub, length = decimal(seq), decimal(minStub), decimal(length)
  if not seq or not minStub or length ~= #core then return status("bad_format", { detail = "envelope_values" }) end
  if kid ~= s_sub(policy.release_key, 1, 16) then return status("unknown_key", { version = version, epoch = policy.epoch }) end
  local header = s_sub(packet, 1, #packet - 129)
  local t0 = os.clock()
  if not verify.verify(hexbytes(policy.release_key), header .. core, hexbytes(sig)) then
    return status("tampered", { version = version, epoch = policy.epoch })
  end
  local verifyMs = math.floor((os.clock() - t0) * 1000 + 0.5)   --CPU time of the signature check, for the record
  if minStub > STUB_VERSION then return status("stub_old", { version = version, sequence = seq }) end

  --5. Never go backwards; the same sequence must be the very same signed release.
  local digest = sha512hex(header .. core)
  if seq < floor or (seq == floor and floorDigest ~= digest) then
    return status("rollback", { version = version, sequence = seq, detail = s_format("accepted %d", floor) })
  end

  --6. Compile exactly the verified bytes, as text only (no bytecode, no file path search).
  local chunk, err = load_(core, "@ThorCompanion-core:" .. version, "t", G)
  if not chunk then return status("compile_failed", { version = version, sequence = seq }) end

  --7. Record the accepted release privately before running it.
  if seq > floor or not journal then
    local j = { epoch = policy.epoch, ["policy-sha512"] = policy.digest, ["key-id"] = kid, sequence = seq, ["message-sha512"] = digest }
    if not saveJournal(journal, j) then return status("state_unwritable", { detail = "journal" }) end
  end

  status("ok", { version = version, sequence = seq, keyId = kid, epoch = policy.epoch, verifyMs = verifyMs })
  local ok = xpcall_(chunk, function(e) return s_sub(tostring_(e), 1, 300) end)
  if not ok then status("core_failed", { version = version, sequence = seq }) end
end

if not verifyLoaded then
  status("unsupported_lua")
else
  local ok = pcall_(run)
  if not ok then status("loader_error") end
end
